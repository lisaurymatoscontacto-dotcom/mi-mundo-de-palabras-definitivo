import type { WordCard } from "./index";

function card(
  id: string,
  word: string,
  category: string,
  visual: string,
  syllables: string[],
  readingDifficulty = 1,
  writingDifficulty = Math.min(6, readingDifficulty + 1),
): WordCard {
  return {
    id,
    word,
    category,
    visual,
    visualKind: "emoji",
    visualLicense: "unicode-emoji",
    syllables,
    readingDifficulty,
    writingDifficulty,
    minAge: 4,
    regions: ["latam"],
    demoOnly: true,
  };
}

